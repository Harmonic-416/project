// @vitest-environment jsdom
import React from 'react'
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import PracticeScreen from '../src/tabs/guitar/practice/PracticeScreen.jsx'
const mic = vi.hoisted(() => ({start:vi.fn(async () => true),stop:vi.fn(),restart:vi.fn(),muteFor:vi.fn(),status:'idle',error:null,verdict:null}))
const sound = vi.hoisted(() => ({strum:vi.fn(async () => {}),arpeggiate:vi.fn(async () => {}),stop:vi.fn()}))
vi.mock('../src/tabs/guitar/practice/useLessonListening.js', () => ({useLessonListening: ({onVerdict}) => {mic.verdict = onVerdict; return mic}}))
vi.mock('../src/tabs/guitar/practice/useChordPlayer.js', () => ({useChordPlayer: () => sound}))
vi.mock('../src/tabs/guitar/practice/useLessonCountIn.js', () => ({useLessonCountIn: () => null}))
vi.mock('../src/tabs/guitar/practice/ChangesRun.jsx', () => ({default: () => null}))
beforeEach(() => {vi.useFakeTimers(); mic.start.mockImplementation(async () => true); mic.error=null; mic.status='idle'; sound.strum.mockImplementation(async () => {})})
afterEach(() => {cleanup(); vi.useRealTimers(); localStorage.clear(); vi.clearAllMocks()})
const tick = async (seconds) => {for (let index=0;index<seconds;index++) await act(async () => vi.advanceTimersByTime(1000))}
const begin = async () => {await act(async () => fireEvent.click(screen.getByRole('button',{name:'Start',exact:true}))); await tick(3)}
it.each(['practice','play'])('releases the microphone when %s is stopped', async (mode) => {
  render(<PracticeScreen initialMode={mode} />)
  await begin(); mic.stop.mockClear()
  fireEvent.click(screen.getByRole('button',{name:'Stop',exact:true}))
  expect(mic.stop).toHaveBeenCalledOnce()
  expect(screen.getByRole('button',{name:'Start',exact:true})).toBeTruthy()
})
it('releases the microphone after a checkpoint passes and preserves its unlock', async () => {
  render(<PracticeScreen initialMode="practice" />)
  await begin(); mic.stop.mockClear()
  for (let index=0;index<3;index++) act(() => mic.verdict({verdict:'verified'}))
  expect(mic.stop).toHaveBeenCalledOnce()
  expect(screen.getByRole('button',{name:'Learn A minor'})).toBeTruthy()
  expect(JSON.parse(localStorage.getItem('harmonic.guitar.cleared')).Em).toBe('passed')
})
it('releases the microphone after the uninterrupted Play run completes', async () => {
  render(<PracticeScreen initialMode="play" />)
  await begin(); mic.stop.mockClear()
  await tick(20)
  expect(screen.getByText('chords heard')).toBeTruthy()
  expect(mic.stop).toHaveBeenCalledOnce()
})
it('cancels a pending start without a delayed permission response restarting it', async () => {
  let resolve; mic.start.mockImplementation(() => new Promise((done) => {resolve=done}))
  render(<PracticeScreen initialMode="practice" />)
  fireEvent.click(screen.getByRole('button',{name:'Start',exact:true}))
  expect(screen.getByText('Opening the microphone before the countdown...')).toBeTruthy()
  fireEvent.click(screen.getByRole('button',{name:'Cancel start'}))
  await act(async () => resolve(true))
  expect(screen.getByRole('button',{name:'Start',exact:true})).toBeTruthy()
  expect(screen.queryByText(/Get ready/)).toBeNull()
})
it('cancels a pending start on unmount and stops the mic', async () => {
  let resolve; mic.start.mockImplementation(() => new Promise((done) => {resolve=done}))
  const view=render(<PracticeScreen initialMode="practice" />)
  fireEvent.click(screen.getByRole('button',{name:'Start',exact:true}))
  view.unmount(); expect(mic.stop).toHaveBeenCalled()
  await act(async () => resolve(true))
  expect(screen.queryByText(/Get ready/)).toBeNull()
})
it('stops a Hint on chord navigation and ignores its late failure', async () => {
  localStorage.setItem('harmonic.guitar.cleared',JSON.stringify({Em:'passed'}))
  let reject; sound.strum.mockImplementation(() => new Promise((_,fail) => {reject=fail}))
  render(<PracticeScreen />)
  fireEvent.click(screen.getByRole('button',{name:'Hint',exact:true}))
  fireEvent.click(screen.getByText(/Choose a chord/))
  fireEvent.click(screen.getByRole('button',{name:'A minor',exact:true}))
  expect(sound.stop).toHaveBeenCalled()
  await act(async () => reject(new Error('Late audio error')))
  expect(screen.queryByRole('alert')).toBeNull()
  expect(screen.getByRole('img',{name:'A minor chord diagram'})).toBeTruthy()
})
it('clears old verdict text on Retry', () => {
  render(<PracticeScreen />)
  fireEvent.click(screen.getByText('Mark it yourself',{exact:true}))
  fireEvent.click(screen.getByRole('button',{name:'A wrong chord'}))
  expect(screen.getByText('Heard: a wrong chord')).toBeTruthy()
  fireEvent.click(screen.getByRole('button',{name:'Retry',exact:true}))
  expect(screen.queryByText('Heard: a wrong chord')).toBeNull()
})
it('offers a manual run after microphone failure and hides that start during the run', async () => {
  mic.start.mockRejectedValueOnce(new Error('No microphone'))
  render(<PracticeScreen initialMode="practice" />)
  await act(async () => fireEvent.click(screen.getByRole('button',{name:'Start',exact:true})))
  fireEvent.click(screen.getByRole('button',{name:'Start without microphone'}))
  expect(screen.queryByRole('button',{name:'Start without microphone'})).toBeNull()
  await tick(3)
  fireEvent.click(screen.getByText('Mark it yourself',{exact:true}))
  for (let index=0;index<3;index++) fireEvent.click(screen.getByRole('button',{name:'The right chord'}))
  expect(screen.getByRole('button',{name:'Learn A minor'})).toBeTruthy()
  expect(mic.start).toHaveBeenCalledOnce()
})
it('resets an active Play run safely when unlocks are reset', async () => {
  render(<PracticeScreen initialMode="play" />)
  await begin()
  fireEvent.click(screen.getByText('Mark it yourself',{exact:true}))
  fireEvent.click(screen.getByRole('button',{name:'Reset unlocks'}))
  expect(screen.getByRole('img',{name:'E minor chord diagram'})).toBeTruthy()
  expect(screen.queryByRole('button',{name:'Stop',exact:true})).toBeNull()
  expect(mic.stop).toHaveBeenCalled()
})

it('does not report microphone verdicts during the pre-run countdown', async () => {
  render(<PracticeScreen initialMode="practice" />)
  await act(async () => fireEvent.click(screen.getByRole('button',{name:'Start',exact:true})))
  act(() => mic.verdict({verdict:'wrong'}))
  expect(screen.queryByText('Heard: a wrong chord')).toBeNull()
  await tick(3)
  fireEvent.click(screen.getByText('Mark it yourself',{exact:true}))
  expect(screen.getByRole('button',{name:'A wrong chord'}).disabled).toBe(false)
})
